def escape(val):
    """Escape a value for a SQL literal."""
    if val is None:
        return "NULL"
    if isinstance(val, bool):
        return "TRUE" if val else "FALSE"
    if isinstance(val, (int, float)):
        return str(val)
    escaped = str(val).replace("'", "''")
    return f"'{escaped}'"


def fetch_all(cursor, table):
    try:
        cursor.execute(f"SELECT * FROM {table}")
        return cursor.fetchall()
    except Exception as e:
        print(f"  ⚠️ Warning fetching {table}: {e}")
        return []


def rows_to_insert(rows, table, conflict_col="id", exclude=None):
    """Generate INSERT ... ON CONFLICT (conflict_col) DO NOTHING statements."""
    if not rows:
        return ""

    exclude = exclude or set()
    lines = []
    for row in rows:
        cols = [k for k in row.keys() if k not in exclude]
        col_str = ", ".join(cols)
        val_str = ", ".join(escape(row[c]) for c in cols)
        lines.append(
            f"INSERT INTO {table} ({col_str}) VALUES ({val_str}) ON CONFLICT ({conflict_col}) DO NOTHING;"
        )
    return "\n".join(lines)


def generate_ddl():
    """Generate CREATE TABLE IF NOT EXISTS statements from SQLAlchemy metadata."""
    ddl_statements = []
    for table in Base.metadata.sorted_tables:
        raw_ddl = str(CreateTable(table).compile(dialect=postgresql.dialect())).strip()
        # Change CREATE TABLE to CREATE TABLE IF NOT EXISTS
        if raw_ddl.startswith("CREATE TABLE "):
            raw_ddl = "CREATE TABLE IF NOT EXISTS " + raw_ddl[len("CREATE TABLE "):]
        ddl_statements.append(raw_ddl + ";")
    return "\n\n".join(ddl_statements)


